"""Regenerate docs/contract.js (address + chain config) from contracts/deployment.json.
Run after every (re)deploy so the website and console can never point at a stale contract:  python scripts/sync_site.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(ROOT, "contracts", "deployment.json")))
cfg = {
    "address": d["address"], "deployBlock": d["block"], "deployTx": d["deployTx"], "chainId": d["chainId"],
    "rpc": "https://testnet-rpc.monad.xyz", "explorer": "https://testnet.monadscan.com",
    "vision": "https://testnet.monadvision.com",
}
open(os.path.join(ROOT, "docs", "contract.js"), "w").write(
    "/* generated by scripts/sync_site.py from contracts/deployment.json - do not edit */\n"
    "window.GUARDVAULT = " + json.dumps(cfg, indent=2) + ";\n")
print("wrote docs/contract.js ->", d["address"])
