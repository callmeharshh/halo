"""Regenerate docs/contract.js (address + chain config) from contracts/deployment.json.
Run after every (re)deploy so the website and console can never point at a stale contract:  python scripts/sync_site.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(ROOT, "contracts", "deployment.json")))
cfg = {
    "address": d["address"], "deployBlock": d["block"], "deployTx": d["deployTx"], "chainId": d["chainId"],
    "rpc": "https://rpc.ankr.com/monad_testnet",
    # Ankr first: measured 25/25 browser reads vs ~68% on testnet-rpc.monad.xyz (empty eth_call results under load)
    "rpcs": ["https://rpc.ankr.com/monad_testnet", "https://testnet-rpc.monad.xyz"], "explorer": "https://testnet.monadscan.com",
    "vision": "https://testnet.monadvision.com",
}
text = ("/* generated by scripts/sync_site.py from contracts/deployment.json - do not edit */\n"
        "window.GUARDVAULT = " + json.dumps(cfg, indent=2) + ";\n")
for folder in ("docs", "ui"):
    open(os.path.join(ROOT, folder, "contract.js"), "w").write(text)
print("wrote docs/contract.js and ui/contract.js ->", d["address"])

# AccessRegistry (travel agent) config for the site and the app
reg = os.path.join(ROOT, "contracts", "deployment.AccessRegistry.json")
if os.path.exists(reg):
    r = json.load(open(reg))
    rcfg = {"address": r["address"], "deployBlock": r["block"], "deployTx": r["deployTx"], "chainId": r["chainId"],
            "rpc": cfg["rpc"], "rpcs": cfg["rpcs"], "explorer": cfg["explorer"], "vision": cfg["vision"]}
    rtext = ("/* generated by scripts/sync_site.py from contracts/deployment.AccessRegistry.json - do not edit */\n"
             "window.ACCESSREG = " + json.dumps(rcfg, indent=2) + ";\n")
    for folder in ("docs", "ui"):
        open(os.path.join(ROOT, folder, "registry.js"), "w").write(rtext)
    print("wrote docs/registry.js and ui/registry.js ->", r["address"])
